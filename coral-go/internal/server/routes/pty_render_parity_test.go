// The PTY backend's raw output, rendered (internal/vtscreen), shows the same rows tmux captured for the same
// screen (#4543): the end of each screen, row for row, up to the project folder's name (the PTY and tmux
// captures were taken in two folders).
func TestPTYRenderMatchesTheTmuxCapture(t *testing.T) {
	lastRows := func(screen string, n int) []string {
		var rows []string
		for _, l := range strings.Split(screen, "\n") {
			l = strings.TrimRight(strings.ReplaceAll(l, "project2", "project"), " ")
			if strings.TrimSpace(l) != "" {
				rows = append(rows, l)
			}
		}
		return rows[max(0, len(rows)-n):]
	}
	for _, c := range []struct {
		pty, tmux string
		rows      int
		read      func(*testing.T, string) string
	}{
		{"pty_open.raw", "tmux_open.txt", 7, codexHookTrust},
		{"pty_selected_2.raw", "tmux_selected_2.txt", 7, codexHookTrust},
		{"pty_trust.raw", "trust.txt", 10, claudeUnnumbered},
		{"pty_trust_yes.raw", "trust_yes.txt", 10, claudeUnnumbered},
		{"pty_apikey.raw", "apikey.txt", 7, claudeUnnumbered},
		{"pty_apikey_yes.raw", "apikey_yes.txt", 7, claudeUnnumbered},
		{"pty_ready.raw", "ready.txt", 2, claudeUnnumbered}, // the input box above shows a random tip each run
	} {
		rendered := ptymanager.RenderScreen([]byte(c.read(t, c.pty)), 120, 40)
		assert.Equal(t, lastRows(c.read(t, c.tmux), c.rows), lastRows(rendered, c.rows), "%s against %s", c.pty, c.tmux)
	}
}

// #77 (audit F11): real screens from Claude Code, Codex 0.161 and agy on Windows ConPTY, captured through Coral's PTY
// (start, idle, a slash menu, /status output, a 70-row answer scrolled off, and resized to 100x35; the user name
// redacted), are rendered by internal/vtscreen to exactly what an independent terminal emulator (pyte) shows for the same
// bytes: every row of every state. The expected text was generated by pyte, not by Coral's renderer.
func TestPTYRenderMatchesAnIndependentEmulatorOnRealAgentScreens(t *testing.T) {
	files, err := filepath.Glob("testdata/pty_render/*.raw")
	require.NoError(t, err)
	require.GreaterOrEqual(t, len(files), 10, "the captured screens are there")
	sizeRe := regexp.MustCompile(`_(\d+)x(\d+)\.raw$`)
	for _, f := range files {
		m := sizeRe.FindStringSubmatch(f)
		require.NotNil(t, m, f)
		cols, _ := strconv.Atoi(m[1])
		rows, _ := strconv.Atoi(m[2])
		raw, err := os.ReadFile(f)
		require.NoError(t, err)
		want, err := os.ReadFile(strings.TrimSuffix(f, ".raw") + ".expected.txt")
		require.NoError(t, err)
		wantRows := strings.Split(strings.TrimSuffix(string(want), "\n"), "\n")
		gotRows := strings.Split(ptymanager.RenderScreen(raw, cols, rows), "\n")
		for len(gotRows) < rows {
			gotRows = append(gotRows, "")
		}
		require.Len(t, wantRows, rows, f)
		for i := range wantRows {
			assert.Equal(t, rtrim(wantRows[i]), rtrim(gotRows[i]), "%s row %d", filepath.Base(f), i+1)
		}
		// Rendering only the end of the output (the replay ring wrapped) shows the same screen for these ConPTY streams, which
		// repaint rows with absolute positions.
		if len(raw) > 6000 {
			tail := strings.Split(ptymanager.RenderScreen(raw[len(raw)-6000:], cols, rows), "\n")
			diff := 0
			for i := range wantRows {
				if i < len(tail) && rtrim(tail[i]) != rtrim(wantRows[i]) {
					diff++
				}
			}
			assert.LessOrEqual(t, diff, 3, "%s: the last 6 KB alone shows (nearly) the same screen", filepath.Base(f))
		}
	}
}

// rtrim drops trailing white space, a no-break space included (the emulator that wrote the expected text does).
func rtrim(s string) string { return strings.TrimRightFunc(s, unicode.IsSpace) }

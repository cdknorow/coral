// Generates static/csp_shapes.js: the allowlist of inline-handler SHAPES that csp_compat.js
// will run, derived from every on*= handler in the shipped UI (JS template literals and HTML
// templates). Template holes are normalised: a quoted hole is a string, Number(...) is a number,
// jsIdent(...) expands to each allowed function name.
//
//   node tools/gen_handler_shapes.mjs           write the file
//   node tools/gen_handler_shapes.mjs --check   fail if the committed file is stale (CI)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanAttributes } from './attr_holes.mjs';
import { shapeOf } from '../coral-go/pkg/frontend/static/csp_parse.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../coral-go/pkg/frontend');
const OUT = path.join(root, 'static/csp_shapes.js');

// Names jsIdent() may emit; a test keeps this in sync with HANDLER_NAMES in utils.js.
export const DYNAMIC_CALLEES = ['toggleEventFilter', 'toggleHistoryEventFilter', 'toggleAllEventFilters', 'toggleAllHistoryEventFilters', 'window._selectAgentPreset', 'window._applyACFPresetValue'];
// Handler strings built into a variable and interpolated whole (render.js clickHandler).
const PREBUILT = ["selectHistorySession('X')", "selectLiveSession('X', 'X', 'X', 'X')"];

const EVENT_ATTR = /^on([a-z]+)$/;
const shapes = new Set();
const events = new Set();

function addVariants(parts) {
    let outs = [''];
    for (const p of parts) {
        const alts = Array.isArray(p) ? p : [p];
        outs = outs.flatMap(o => alts.map(a => o + a));
    }
    return outs;
}

function handle(attrName, parts) {
    const m = EVENT_ATTR.exec(attrName);
    if (!m) return;
    events.add(m[1]);
    for (const src of addVariants(parts)) {
        try { shapes.add(shapeOf(src.replace(/&quot;/g, '"').replace(/&#39;/g, "'"))); }
        catch (e) { throw new Error(`handler outside the grammar: ${src.slice(0, 120)} (${e.message})`); }
    }
}

function expandHole(expr, quoted) {
    const t = expr.trim();
    if (/^jsStr\(/.test(t)) return 'X';
    if (/^Number\(/.test(t)) return '0';
    if (/^jsIdent\(/.test(t)) return DYNAMIC_CALLEES;
    const lit = /^[^?]*\?\s*('([^'\\]*)'|"([^"\\]*)")\s*:\s*('([^'\\]*)'|"([^"\\]*)")\s*$/.exec(t);
    if (lit) return [lit[2] ?? lit[3], lit[5] ?? lit[6]];
    if (t === 'clickHandler') return PREBUILT;
    return quoted ? 'X' : '0'; // unreviewed holes are rejected by the attribute lint, not here
}

const staticDir = path.join(root, 'static');
for (const f of fs.readdirSync(staticDir).filter(x => x.endsWith('.js')).sort()) {
    const src = fs.readFileSync(path.join(staticDir, f), 'utf8');
    for (const a of scanAttributes(src)) {
        if (!EVENT_ATTR.test(a.name)) continue;
        let inQuote = false;
        const parts = [];
        for (const p of a.parts) {
            if (p.kind === 'text') {
                const text = src.slice(p.s, p.e);
                for (let k = 0; k < text.length; k++) { if (text[k] === '\\') { k++; continue; } if (text[k] === "'") inQuote = !inQuote; }
                parts.push(text.replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\\\/g, '\\'));
            } else {
                parts.push(expandHole(src.slice(p.s, p.e), inQuote));
            }
        }
        handle(a.name, parts);
    }
}
for (const p of PREBUILT) shapes.add(shapeOf(p));

function walk(d, out) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); e.isDirectory() ? walk(p, out) : /\.html$/.test(e.name) && out.push(p); } return out; }
for (const f of walk(path.join(root, 'templates'), [])) {
    const html = fs.readFileSync(f, 'utf8');
    const re = /\son([a-z]+)="([^"]*)"/g;
    let m;
    while ((m = re.exec(html))) handle('on' + m[1], [m[2].replace(/&quot;/g, '"').replace(/&#39;/g, "'")]);
}

const sorted = [...shapes].sort();
const body = `/* GENERATED by tools/gen_handler_shapes.mjs from the on*= handlers in the shipped UI. Do not edit.
 * csp_compat.js runs only handlers whose shape (csp_parse.shapeOf) is listed here. Regenerate with
 *   node tools/gen_handler_shapes.mjs
 * CI runs it with --check. */

export const EVENTS = ${JSON.stringify([...events].sort())};

export const SHAPES = new Set(${JSON.stringify(sorted, null, 4)});
`;

if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== body) { console.error('csp_shapes.js is stale: run `node tools/gen_handler_shapes.mjs` and commit the result'); process.exit(1); }
    console.log(`csp_shapes.js up to date (${sorted.length} shapes, events: ${[...events].sort().join(',')})`);
} else {
    fs.writeFileSync(OUT, body);
    console.log(`wrote ${sorted.length} shapes, events: ${[...events].sort().join(',')}`);
}
